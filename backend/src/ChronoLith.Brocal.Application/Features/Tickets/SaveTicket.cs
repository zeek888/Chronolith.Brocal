namespace ChronoLith.Brocal.Application.Features.Tickets;

/// <summary>Line as captured in the field; the price comes from the price lists unless the user may override it.</summary>
public sealed record TicketLineInput(Guid ServiceId, decimal Quantity, decimal? UnitPrice, string? Description);

/// <summary>Odometer / hour meter of a unit read at the end of the service.</summary>
public sealed record UnitMeterInput(Guid UnitId, decimal? Odometer, decimal? Hours);

public sealed record SaveTicketResult(Guid Id, string Folio, bool Created, IReadOnlyList<string> Warnings);

/// <summary>
/// Creates or updates a draft ticket. Offline captures send the id generated by the device (<see cref="ClientId"/>):
/// sending the same ticket twice returns the one already stored instead of duplicating it.
/// </summary>
public sealed record SaveTicketCommand(
    Guid? Id,
    Guid? ClientId,
    TicketData Data,
    IReadOnlyList<TicketLineInput> Lines,
    IReadOnlyList<UnitMeterInput>? Meters) : ICommand<SaveTicketResult>;

internal sealed class SaveTicketCommandValidator : AbstractValidator<SaveTicketCommand>
{
    public SaveTicketCommandValidator()
    {
        RuleFor(c => c.Data).NotNull();
        RuleFor(c => c.Data.CustomerId).RequiredId("el cliente");
        RuleFor(c => c.Data.SiteId).RequiredId("la locación o pozo");
        RuleFor(c => c.Data.ServiceTypeId).RequiredId("el tipo de servicio");
        RuleFor(c => c.Data.Description).OptionalText(4000);
        RuleFor(c => c.Data.Observations).OptionalText(4000);
        RuleForEach(c => c.Lines).ChildRules(line =>
        {
            line.RuleFor(l => l.ServiceId).NotEmpty();
            line.RuleFor(l => l.Quantity).GreaterThanOrEqualTo(0).LessThan(1_000_000);
            line.RuleFor(l => l.UnitPrice).GreaterThanOrEqualTo(0).When(l => l.UnitPrice is not null);
            line.RuleFor(l => l.Description).MaximumLength(500);
        });
    }
}

internal sealed class SaveTicketCommandHandler(
    IApplicationDbContext db,
    ITenantContext tenant,
    IUserContext user,
    IFolioService folios,
    IQuotaGuard quotas,
    ITenantClock clock) : ICommandHandler<SaveTicketCommand, SaveTicketResult>
{
    public async Task<Result<SaveTicketResult>> Handle(SaveTicketCommand command, CancellationToken cancellationToken)
    {
        if (command.Id is null && command.ClientId is { } clientId)
        {
            // Idempotent offline sync: the device retries until it gets an answer.
            var existing = await db.Tickets.AsNoTracking().Where(t => t.ClientId == clientId).Select(t => new { t.Id, t.Folio }).FirstOrDefaultAsync(cancellationToken);
            if (existing is not null)
            {
                return new SaveTicketResult(existing.Id, existing.Folio, false, ["La boleta ya estaba sincronizada."]);
            }
        }

        var references = await ValidateReferencesAsync(command.Data, cancellationToken);
        if (references.IsFailure)
        {
            return references.Error;
        }

        var priced = await PriceLinesAsync(command, cancellationToken);
        if (priced.IsFailure)
        {
            return priced.Error;
        }

        var (lines, warnings) = priced.Value;
        return command.Id is null
            ? await CreateAsync(command, lines, warnings, cancellationToken)
            : await UpdateAsync(command.Id.Value, command, lines, warnings, cancellationToken);
    }

    private async Task<Result<SaveTicketResult>> CreateAsync(SaveTicketCommand command, IReadOnlyList<PricedLine> lines, List<string> warnings, CancellationToken cancellationToken)
    {
        var quota = await quotas.EnsureCanAddTicketAsync(cancellationToken);
        if (quota.IsFailure)
        {
            return quota.Error;
        }

        return await db.ExecuteInTransactionAsync(async ct =>
        {
            var number = await folios.NextAsync(FolioKeys.Ticket, ct);
            var folio = FolioSequence.Format(tenant.Tenant.Settings.TicketPrefix, number);
            var created = ServiceTicket.Create(
                Guid.CreateVersion7(),
                folio,
                number,
                command.ClientId,
                command.Data,
                lines,
                tenant.Membership?.Id,
                tenant.Membership?.FullName ?? user.DisplayName,
                tenant.Tenant.Settings.Currency);

            if (created.IsFailure)
            {
                return Result.Failure<SaveTicketResult>(created.Error);
            }

            var ticket = created.Value;
            var type = await db.ServiceTypes.AsNoTracking().FirstAsync(t => t.Id == ticket.ServiceTypeId, ct);
            var answers = type.ValidateAnswers(ticket.Answers, requireComplete: false);
            if (answers.IsFailure)
            {
                return Result.Failure<SaveTicketResult>(answers.Error);
            }

            db.Tickets.Add(ticket);

            if (ticket.WorkOrderId is { } workOrderId)
            {
                var order = await db.WorkOrders.FirstOrDefaultAsync(w => w.Id == workOrderId, ct);
                order?.TicketCaptured(clock.UtcNow);
            }

            var meters = await RecordMetersAsync(command.Meters, ticket.Id, ct);
            if (meters.IsFailure)
            {
                return Result.Failure<SaveTicketResult>(meters.Error);
            }

            await db.SaveChangesAsync(ct);
            return Result.Success(new SaveTicketResult(ticket.Id, ticket.Folio, true, warnings));
        }, cancellationToken);
    }

    private async Task<Result<SaveTicketResult>> UpdateAsync(Guid id, SaveTicketCommand command, IReadOnlyList<PricedLine> lines, List<string> warnings, CancellationToken cancellationToken)
    {
        var ticket = await db.Tickets.Visible(tenant).Include(t => t.Lines).FirstOrDefaultAsync(t => t.Id == id, cancellationToken);
        if (ticket is null)
        {
            return TicketErrors.NotFound;
        }

        var result = ticket.Update(command.Data, lines);
        if (result.IsFailure)
        {
            return result.Error;
        }

        var type = await db.ServiceTypes.AsNoTracking().FirstAsync(t => t.Id == ticket.ServiceTypeId, cancellationToken);
        var answers = type.ValidateAnswers(ticket.Answers, requireComplete: false);
        if (answers.IsFailure)
        {
            return answers.Error;
        }

        var meters = await RecordMetersAsync(command.Meters, ticket.Id, cancellationToken);
        if (meters.IsFailure)
        {
            return meters.Error;
        }

        await db.SaveChangesAsync(cancellationToken);
        return new SaveTicketResult(ticket.Id, ticket.Folio, false, warnings);
    }

    private async Task<Result> ValidateReferencesAsync(TicketData data, CancellationToken cancellationToken)
    {
        var checks = new[]
        {
            await References.EnsureAsync<Customer>(db, data.CustomerId, CustomerErrors.Catalog, cancellationToken),
            await References.EnsureAsync<Site>(db, data.SiteId, SiteErrors.Catalog, cancellationToken),
            await References.EnsureAsync<ServiceType>(db, data.ServiceTypeId, ServiceTypeErrors.Catalog, cancellationToken),
            await References.EnsureAllAsync<Unit>(db, data.UnitIds, UnitErrors.Catalog, cancellationToken),
            await References.EnsureAllAsync<Employee>(db, data.EmployeeIds, EmployeeErrors.Catalog, cancellationToken),
            await References.EnsureAsync<Crew>(db, data.CrewId, "Crews", cancellationToken)
        };

        var failure = Result.FirstFailure(checks);
        if (failure.IsFailure)
        {
            return failure;
        }

        if (data.ContractId is not null)
        {
            var contract = await db.Contracts.AsNoTracking().FirstOrDefaultAsync(c => c.Id == data.ContractId, cancellationToken);
            if (contract is null || contract.CustomerId != data.CustomerId)
            {
                return ContractErrors.CustomerMismatch;
            }
        }

        if (data.WorkOrderId is not null)
        {
            var order = await db.WorkOrders.AsNoTracking().FirstOrDefaultAsync(w => w.Id == data.WorkOrderId, cancellationToken);
            if (order is null)
            {
                return WorkOrderErrors.NotFound;
            }

            if (order.CustomerId != data.CustomerId)
            {
                return Error.Validation("Tickets.WorkOrderCustomer", "La orden de trabajo es de otro cliente.");
            }

            if (order.Status == WorkOrderStatus.Cancelled)
            {
                return Error.Validation("Tickets.WorkOrderCancelled", "La orden de trabajo está cancelada.");
            }
        }

        return Result.Success();
    }

    private async Task<Result<(IReadOnlyList<PricedLine> Lines, List<string> Warnings)>> PriceLinesAsync(SaveTicketCommand command, CancellationToken cancellationToken)
    {
        var serviceIds = command.Lines.Select(l => l.ServiceId).Distinct().ToList();
        var services = await db.Services.AsNoTracking().Where(s => serviceIds.Contains(s.Id)).ToDictionaryAsync(s => s.Id, cancellationToken);
        if (services.Count != serviceIds.Count)
        {
            return CatalogErrors.ReferenceNotFound(ServiceErrors.Catalog);
        }

        var book = await PriceBook.LoadAsync(db, cancellationToken);
        var canOverride = tenant.Has(Permissions.TicketsPriceOverride);
        var warnings = new List<string>();
        var lines = new List<PricedLine>();

        foreach (var input in command.Lines)
        {
            var service = services[input.ServiceId];
            var resolved = book.Resolve(command.Data.CustomerId, command.Data.ContractId, service.Id, command.Data.ServiceDate, service.BasePrice);
            var price = resolved.UnitPrice ?? 0;
            var source = resolved.Source;

            if (input.UnitPrice is { } manual && manual != price)
            {
                if (canOverride)
                {
                    price = manual;
                    source = PriceSource.Manual;
                }
                else
                {
                    warnings.Add($"Se aplicó el precio del tarifario a '{service.Name}'.");
                }
            }

            if (resolved.UnitPrice is null && source != PriceSource.Manual)
            {
                warnings.Add($"'{service.Name}' no tiene precio para este cliente; la oficina debe revisarlo.");
            }

            var description = string.IsNullOrWhiteSpace(input.Description) ? service.Name : input.Description.Trim();
            lines.Add(new PricedLine(service.Id, description, input.Quantity, service.UnitName, price, source, service.VatRate));
        }

        return (lines, warnings);
    }

    private async Task<Result> RecordMetersAsync(IReadOnlyList<UnitMeterInput>? meters, Guid ticketId, CancellationToken cancellationToken)
    {
        foreach (var meter in (meters ?? []).Where(m => m.Odometer is not null || m.Hours is not null))
        {
            var unit = await db.Units.FirstOrDefaultAsync(u => u.Id == meter.UnitId, cancellationToken);
            if (unit is null)
            {
                return CatalogErrors.ReferenceNotFound(UnitErrors.Catalog);
            }

            var result = unit.RecordMeters(meter.Odometer, meter.Hours, clock.UtcNow);
            if (result.IsFailure)
            {
                return Error.Validation(result.Error.Code, $"{unit.Code}: {result.Error.Description}");
            }

            db.UnitMeterReadings.Add(new UnitMeterReading(unit.Id, clock.UtcNow, meter.Odometer, meter.Hours, MeterSource.Ticket, ticketId, null, user.DisplayName));
        }

        return Result.Success();
    }
}
