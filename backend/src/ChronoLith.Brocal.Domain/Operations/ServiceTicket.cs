using ChronoLith.Brocal.Domain.Abstractions;
using ChronoLith.Brocal.Domain.Commercial;
using ChronoLith.Brocal.Domain.Common;
using ChronoLith.Brocal.Domain.Platform;

namespace ChronoLith.Brocal.Domain.Operations;

public enum TicketStatus
{
    /// <summary>Being captured in the field (editable).</summary>
    Draft = 0,

    /// <summary>Closed with the customer's signature (or without it when the service type allows it).</summary>
    Signed = 1,

    /// <summary>Reviewed by the office, ready to invoice.</summary>
    Approved = 2,

    /// <summary>Included in a CFDI.</summary>
    Invoiced = 3,

    Cancelled = 4
}

/// <summary>Billable line of a ticket. The price is frozen when the line is captured (it is not negotiated at the well).</summary>
public sealed class TicketLine : TenantEntity
{
    private TicketLine()
    {
    }

    internal TicketLine(int order, Guid serviceId, string description, decimal quantity, string unitName, decimal unitPrice, PriceSource priceSource, decimal vatRate)
    {
        Order = order;
        ServiceId = serviceId;
        Description = description;
        Quantity = quantity;
        UnitName = unitName;
        UnitPrice = unitPrice;
        PriceSource = priceSource;
        VatRate = vatRate;
        Amount = Money.Round(quantity * unitPrice);
    }

    public Guid TicketId { get; private set; }

    public int Order { get; private set; }

    public Guid ServiceId { get; private set; }

    public string Description { get; private set; } = null!;

    public decimal Quantity { get; private set; }

    public string UnitName { get; private set; } = null!;

    public decimal UnitPrice { get; private set; }

    public PriceSource PriceSource { get; private set; }

    public decimal VatRate { get; private set; }

    public decimal Amount { get; private set; }

    public decimal Vat => Money.Round(Amount * VatRate);
}

/// <summary>Photo evidence taken in the field.</summary>
public sealed class TicketPhoto : TenantEntity
{
    private TicketPhoto()
    {
    }

    internal TicketPhoto(Guid fileId, string? caption, DateTimeOffset takenAt, GeoPoint? location, int order)
    {
        FileId = fileId;
        Caption = caption;
        TakenAt = takenAt;
        Latitude = location?.Latitude;
        Longitude = location?.Longitude;
        Order = order;
    }

    public Guid TicketId { get; private set; }

    public Guid FileId { get; private set; }

    public string? Caption { get; private set; }

    public DateTimeOffset TakenAt { get; private set; }

    public decimal? Latitude { get; private set; }

    public decimal? Longitude { get; private set; }

    public int Order { get; private set; }
}

/// <summary>Data captured for a ticket (create and edit while it is a draft).</summary>
public sealed record TicketData(
    Guid CustomerId,
    Guid? ContractId,
    Guid SiteId,
    Guid ServiceTypeId,
    Guid? WorkOrderId,
    DateOnly ServiceDate,
    DateTimeOffset? StartedAt,
    DateTimeOffset? FinishedAt,
    IReadOnlyList<Guid>? UnitIds,
    Guid? CrewId,
    IReadOnlyList<Guid>? EmployeeIds,
    string? Description,
    string? Observations,
    string? CustomerRepresentative,
    IReadOnlyDictionary<string, string?>? Answers,
    GeoPoint? CaptureLocation);

/// <summary>Line to price: the application resolves the price from the price lists before calling the aggregate.</summary>
public sealed record PricedLine(Guid ServiceId, string Description, decimal Quantity, string UnitName, decimal UnitPrice, PriceSource PriceSource, decimal VatRate);

public sealed record TicketSignedEvent(Guid TicketId) : IDomainEvent;

public sealed record TicketCancelledEvent(Guid TicketId) : IDomainEvent;

/// <summary>
/// Boleta de servicio: evidence of a service delivered to a customer at a site. It is captured in the field (even
/// offline: <see cref="ClientId"/> makes the sync idempotent), signed by the customer and later approved and
/// invoiced. Once signed it cannot be edited unless reopened with a reason (audited).
/// </summary>
public sealed class ServiceTicket : TenantAggregateRoot, IAuditReference
{
    private readonly List<TicketLine> _lines = [];
    private readonly List<TicketPhoto> _photos = [];
    private List<Guid> _unitIds = [];
    private List<Guid> _employeeIds = [];
    private Dictionary<string, string?> _answers = [];

    private ServiceTicket()
    {
    }

    private ServiceTicket(Guid id)
        : base(id)
    {
    }

    public string Folio { get; private set; } = null!;

    public long FolioNumber { get; private set; }

    /// <summary>Id generated by the device that captured it offline (unique per company).</summary>
    public Guid? ClientId { get; private set; }

    public TicketStatus Status { get; private set; } = TicketStatus.Draft;

    public Guid CustomerId { get; private set; }

    public Guid? ContractId { get; private set; }

    public Guid SiteId { get; private set; }

    public Guid ServiceTypeId { get; private set; }

    public Guid? WorkOrderId { get; private set; }

    public DateOnly ServiceDate { get; private set; }

    public DateTimeOffset? StartedAt { get; private set; }

    public DateTimeOffset? FinishedAt { get; private set; }

    public IReadOnlyList<Guid> UnitIds => _unitIds;

    public Guid? CrewId { get; private set; }

    /// <summary>Personnel that took part in the service (job costing, "my tickets").</summary>
    public IReadOnlyList<Guid> EmployeeIds => _employeeIds;

    /// <summary>Work performed.</summary>
    public string? Description { get; private set; }

    public string? Observations { get; private set; }

    /// <summary>Customer representative at the site (company man, residente).</summary>
    public string? CustomerRepresentative { get; private set; }

    /// <summary>Answers of the dynamic form of the service type.</summary>
    public IReadOnlyDictionary<string, string?> Answers => _answers;

    public decimal? CaptureLatitude { get; private set; }

    public decimal? CaptureLongitude { get; private set; }

    public IReadOnlyList<TicketLine> Lines => _lines;

    public IReadOnlyList<TicketPhoto> Photos => _photos;

    public string Currency { get; private set; } = "MXN";

    public decimal Subtotal { get; private set; }

    public decimal Vat { get; private set; }

    public decimal Total { get; private set; }

    /// <summary>Membership that captured the ticket.</summary>
    public Guid? CapturedById { get; private set; }

    public string? CapturedByName { get; private set; }

    public string? SignerName { get; private set; }

    public string? SignerPosition { get; private set; }

    public Guid? SignatureFileId { get; private set; }

    public DateTimeOffset? SignedAt { get; private set; }

    public decimal? SignedLatitude { get; private set; }

    public decimal? SignedLongitude { get; private set; }

    public DateTimeOffset? ApprovedAt { get; private set; }

    public string? ApprovedBy { get; private set; }

    public Guid? InvoiceId { get; private set; }

    public DateTimeOffset? InvoicedAt { get; private set; }

    public DateTimeOffset? CancelledAt { get; private set; }

    public string? CancellationReason { get; private set; }

    public Guid? PdfFileId { get; private set; }

    public string AuditReference => Folio;

    public bool IsEditable => Status == TicketStatus.Draft;

    public static Result<ServiceTicket> Create(
        Guid id,
        string folio,
        long folioNumber,
        Guid? clientId,
        TicketData data,
        IReadOnlyList<PricedLine> lines,
        Guid? capturedById,
        string? capturedByName,
        string currency)
    {
        var ticket = new ServiceTicket(id)
        {
            Folio = folio,
            FolioNumber = folioNumber,
            ClientId = clientId,
            CapturedById = capturedById,
            CapturedByName = capturedByName,
            Currency = currency
        };

        var result = ticket.Apply(data);
        if (result.IsFailure)
        {
            return result.Error;
        }

        ticket.ReplaceLines(lines);
        return ticket;
    }

    public Result Update(TicketData data, IReadOnlyList<PricedLine> lines)
    {
        if (!IsEditable)
        {
            return TicketErrors.NotEditable;
        }

        var result = Apply(data);
        if (result.IsFailure)
        {
            return result;
        }

        ReplaceLines(lines);
        return Result.Success();
    }

    public Result AddPhoto(Guid fileId, string? caption, DateTimeOffset takenAt, GeoPoint? location)
    {
        if (!IsEditable)
        {
            return TicketErrors.NotEditable;
        }

        if (_photos.Count >= 40)
        {
            return TicketErrors.TooManyPhotos;
        }

        if (_photos.Any(p => p.FileId == fileId))
        {
            return Result.Success();
        }

        _photos.Add(new TicketPhoto(fileId, string.IsNullOrWhiteSpace(caption) ? null : caption.Trim(), takenAt, location is { IsValid: true } ? location : null, _photos.Count + 1));
        return Result.Success();
    }

    public Result RemovePhoto(Guid photoId)
    {
        if (!IsEditable)
        {
            return TicketErrors.NotEditable;
        }

        var photo = _photos.FirstOrDefault(p => p.Id == photoId);
        if (photo is null)
        {
            return TicketErrors.PhotoNotFound;
        }

        _photos.Remove(photo);
        return Result.Success();
    }

    /// <summary>
    /// Closes the ticket with the customer's signature. The form must be complete, it needs at least one line and
    /// the minimum photos of its service type.
    /// </summary>
    public Result Sign(ServiceType type, int tenantMinPhotos, string signerName, string? signerPosition, Guid signatureFileId, DateTimeOffset signedAt, GeoPoint? location)
    {
        var ready = EnsureReadyToClose(type, tenantMinPhotos);
        if (ready.IsFailure)
        {
            return ready;
        }

        if (string.IsNullOrWhiteSpace(signerName) || signerName.Trim().Length > 150)
        {
            return TicketErrors.SignerRequired;
        }

        SignerName = signerName.Trim();
        SignerPosition = string.IsNullOrWhiteSpace(signerPosition) ? null : signerPosition.Trim();
        SignatureFileId = signatureFileId;
        SignedAt = signedAt;
        SignedLatitude = location is { IsValid: true } ? location.Latitude : null;
        SignedLongitude = location is { IsValid: true } ? location.Longitude : null;
        FinishedAt ??= signedAt;
        Status = TicketStatus.Signed;
        Raise(new TicketSignedEvent(Id));

        return Result.Success();
    }

    /// <summary>Closes a ticket whose service type and company settings do not require the customer's signature.</summary>
    public Result CloseWithoutSignature(ServiceType type, int tenantMinPhotos, bool tenantRequiresSignature, DateTimeOffset closedAt)
    {
        if (type.RequiresSignature || tenantRequiresSignature)
        {
            return TicketErrors.SignatureRequired;
        }

        var ready = EnsureReadyToClose(type, tenantMinPhotos);
        if (ready.IsFailure)
        {
            return ready;
        }

        SignedAt = closedAt;
        FinishedAt ??= closedAt;
        Status = TicketStatus.Signed;
        Raise(new TicketSignedEvent(Id));
        return Result.Success();
    }

    public Result Approve(string approvedBy, DateTimeOffset at)
    {
        if (Status != TicketStatus.Signed)
        {
            return TicketErrors.InvalidTransition(Status, TicketStatus.Approved);
        }

        Status = TicketStatus.Approved;
        ApprovedAt = at;
        ApprovedBy = approvedBy;
        return Result.Success();
    }

    public Result EnsureInvoiceable(bool requireApproval)
    {
        if (Status == TicketStatus.Approved || Status == TicketStatus.Signed && !requireApproval)
        {
            return Lines.Count == 0 ? TicketErrors.NoLines : Result.Success();
        }

        return Status == TicketStatus.Signed ? TicketErrors.ApprovalRequired : TicketErrors.NotInvoiceable;
    }

    public Result MarkInvoiced(Guid invoiceId, DateTimeOffset at, bool requireApproval)
    {
        var check = EnsureInvoiceable(requireApproval);
        if (check.IsFailure)
        {
            return check;
        }

        Status = TicketStatus.Invoiced;
        InvoiceId = invoiceId;
        InvoicedAt = at;
        return Result.Success();
    }

    /// <summary>The invoice was cancelled or deleted: the ticket can be invoiced again.</summary>
    public void ReleaseInvoice()
    {
        if (Status != TicketStatus.Invoiced)
        {
            return;
        }

        Status = ApprovedAt is null ? TicketStatus.Signed : TicketStatus.Approved;
        InvoiceId = null;
        InvoicedAt = null;
    }

    public Result Reopen(string reason)
    {
        if (string.IsNullOrWhiteSpace(reason))
        {
            return TicketErrors.ReasonRequired;
        }

        if (Status is not (TicketStatus.Signed or TicketStatus.Approved))
        {
            return TicketErrors.InvalidTransition(Status, TicketStatus.Draft);
        }

        Status = TicketStatus.Draft;
        SignerName = null;
        SignerPosition = null;
        SignatureFileId = null;
        SignedAt = null;
        SignedLatitude = null;
        SignedLongitude = null;
        ApprovedAt = null;
        ApprovedBy = null;
        PdfFileId = null;
        return Result.Success();
    }

    public Result Cancel(string reason, DateTimeOffset at)
    {
        if (string.IsNullOrWhiteSpace(reason))
        {
            return TicketErrors.ReasonRequired;
        }

        if (Status is TicketStatus.Invoiced)
        {
            return TicketErrors.CancelInvoiceFirst;
        }

        if (Status is TicketStatus.Cancelled)
        {
            return TicketErrors.InvalidTransition(Status, TicketStatus.Cancelled);
        }

        Status = TicketStatus.Cancelled;
        CancelledAt = at;
        CancellationReason = reason.Trim();
        Raise(new TicketCancelledEvent(Id));
        return Result.Success();
    }

    public void AttachPdf(Guid fileId) => PdfFileId = fileId;

    /// <summary>Whether the person took part in the ticket (captured it or is listed as personnel).</summary>
    public bool Involves(Guid? membershipId, Guid? employeeId) =>
        membershipId is not null && CapturedById == membershipId || employeeId is not null && _employeeIds.Contains(employeeId.Value);

    private Result EnsureReadyToClose(ServiceType type, int tenantMinPhotos)
    {
        if (Status != TicketStatus.Draft)
        {
            return TicketErrors.InvalidTransition(Status, TicketStatus.Signed);
        }

        if (type.Id != ServiceTypeId)
        {
            return TicketErrors.ServiceTypeMismatch;
        }

        var answers = type.ValidateAnswers(_answers, requireComplete: true);
        if (answers.IsFailure)
        {
            return answers;
        }

        if (_lines.Count == 0)
        {
            return TicketErrors.NoLines;
        }

        var minPhotos = Math.Max(type.MinPhotos, tenantMinPhotos);
        if (_photos.Count < minPhotos)
        {
            return TicketErrors.MissingPhotos(minPhotos);
        }

        return Result.Success();
    }

    private Result Apply(TicketData data)
    {
        if (data.FinishedAt is not null && data.StartedAt is not null && data.FinishedAt < data.StartedAt)
        {
            return TicketErrors.InvalidTimes;
        }

        if (data.Description is { Length: > 4000 } || data.Observations is { Length: > 4000 })
        {
            return TicketErrors.TextTooLong;
        }

        CustomerId = data.CustomerId;
        ContractId = data.ContractId;
        SiteId = data.SiteId;
        ServiceTypeId = data.ServiceTypeId;
        WorkOrderId = data.WorkOrderId;
        ServiceDate = data.ServiceDate;
        StartedAt = data.StartedAt;
        FinishedAt = data.FinishedAt;
        _unitIds = (data.UnitIds ?? []).Distinct().ToList();
        CrewId = data.CrewId;
        _employeeIds = (data.EmployeeIds ?? []).Distinct().ToList();
        Description = string.IsNullOrWhiteSpace(data.Description) ? null : data.Description.Trim();
        Observations = string.IsNullOrWhiteSpace(data.Observations) ? null : data.Observations.Trim();
        CustomerRepresentative = string.IsNullOrWhiteSpace(data.CustomerRepresentative) ? null : data.CustomerRepresentative.Trim();
        _answers = (data.Answers ?? new Dictionary<string, string?>())
            .Where(a => !string.IsNullOrWhiteSpace(a.Key))
            .ToDictionary(a => a.Key.Trim(), a => string.IsNullOrWhiteSpace(a.Value) ? null : a.Value.Trim());
        CaptureLatitude = data.CaptureLocation is { IsValid: true } ? data.CaptureLocation.Latitude : CaptureLatitude;
        CaptureLongitude = data.CaptureLocation is { IsValid: true } ? data.CaptureLocation.Longitude : CaptureLongitude;

        return Result.Success();
    }

    private void ReplaceLines(IReadOnlyList<PricedLine> lines)
    {
        _lines.Clear();
        var order = 1;
        foreach (var line in lines.Where(l => l.Quantity > 0))
        {
            _lines.Add(new TicketLine(order++, line.ServiceId, line.Description, line.Quantity, line.UnitName, line.UnitPrice, line.PriceSource, line.VatRate));
        }

        Subtotal = Money.Round(_lines.Sum(l => l.Amount));
        Vat = Money.Round(_lines.Sum(l => l.Vat));
        Total = Subtotal + Vat;
    }
}

public static class TicketErrors
{
    public static readonly Error NotFound = Error.NotFound("Tickets.NotFound", "La boleta no existe.");

    public static readonly Error NotEditable = Error.Conflict("Tickets.NotEditable", "La boleta ya está cerrada; solo se puede reabrir con un motivo.");

    public static readonly Error InvalidTimes = Error.Validation("Tickets.InvalidTimes", "La hora de término no puede ser anterior a la de inicio.");

    public static readonly Error TextTooLong = Error.Validation("Tickets.TextTooLong", "La descripción y las observaciones admiten hasta 4000 caracteres.");

    public static readonly Error NoLines = Error.Validation("Tickets.NoLines", "Agrega al menos un concepto con cantidad.");

    public static readonly Error SignerRequired = Error.Validation("Tickets.SignerRequired", "Indica el nombre de quien firma por el cliente.");

    public static readonly Error SignatureRequired = Error.Validation("Tickets.SignatureRequired", "Este servicio requiere la firma del cliente.");

    public static readonly Error ServiceTypeMismatch = Error.Validation("Tickets.ServiceTypeMismatch", "El tipo de servicio no corresponde a la boleta.");

    public static readonly Error TooManyPhotos = Error.Validation("Tickets.TooManyPhotos", "Una boleta admite hasta 40 fotos.");

    public static readonly Error PhotoNotFound = Error.NotFound("Tickets.PhotoNotFound", "La foto no existe.");

    public static readonly Error ReasonRequired = Error.Validation("Tickets.ReasonRequired", "Indica el motivo.");

    public static readonly Error CancelInvoiceFirst = Error.Conflict("Tickets.CancelInvoiceFirst", "La boleta está facturada: cancela primero la factura.");

    public static readonly Error ApprovalRequired = Error.Conflict("Tickets.ApprovalRequired", "La boleta debe validarse antes de facturarse.");

    public static readonly Error NotInvoiceable = Error.Conflict("Tickets.NotInvoiceable", "Solo se facturan boletas firmadas o validadas.");

    public static readonly Error DuplicatedClientId = Error.Conflict("Tickets.DuplicatedClientId", "La boleta ya fue sincronizada.");

    public static readonly Error MonthlyQuota = Error.Conflict("Tickets.MonthlyQuota", "Se alcanzó el límite mensual de boletas contratado.");

    public static Error MissingPhotos(int minimum) => Error.Validation("Tickets.MissingPhotos", $"Se requieren al menos {minimum} foto(s) de evidencia.");

    public static Error InvalidTransition(TicketStatus from, TicketStatus to) =>
        Error.Conflict("Tickets.InvalidTransition", $"No se puede pasar la boleta de '{from}' a '{to}'.");
}
