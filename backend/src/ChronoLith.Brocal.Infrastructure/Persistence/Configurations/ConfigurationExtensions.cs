using System.Linq.Expressions;
using System.Text.Json;
using System.Text.Json.Serialization;
using ChronoLith.Brocal.Domain.Abstractions;
using ChronoLith.Brocal.Domain.Common;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.ChangeTracking;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Microsoft.EntityFrameworkCore.Storage.ValueConversion;

namespace ChronoLith.Brocal.Infrastructure.Persistence.Configurations;

internal static class ConfigurationExtensions
{
    internal static readonly JsonSerializerOptions Json = new(JsonSerializerDefaults.Web)
    {
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) }
    };

    /// <summary>Ids are generated by the domain (UUID v7), never by the database.</summary>
    public static void ConfigureEntity<T>(this EntityTypeBuilder<T> builder)
        where T : Entity
    {
        builder.HasKey(e => e.Id);
        builder.Property(e => e.Id).ValueGeneratedNever();
    }

    public static void ConfigureAggregateRoot<T>(this EntityTypeBuilder<T> builder)
        where T : AggregateRoot
    {
        builder.ConfigureEntity();
        builder.Property(e => e.CreatedBy).HasMaxLength(150);
        builder.Property(e => e.UpdatedBy).HasMaxLength(150);
        builder.Property(e => e.RowVersion).IsRowVersion();
        builder.Ignore(e => e.DomainEvents);
    }

    /// <summary>Master data: unique code per company, name, notes and active flag.</summary>
    public static void ConfigureCatalog<T>(this EntityTypeBuilder<T> builder, string table)
        where T : CatalogAggregate
    {
        builder.ToTable(table);
        builder.ConfigureAggregateRoot();
        builder.Property(e => e.Code).HasMaxLength(Codes.MaxLength).IsRequired();
        builder.Property(e => e.Name).HasMaxLength(CatalogAggregate.MaxNameLength).IsRequired();
        builder.Property(e => e.Notes).HasMaxLength(CatalogAggregate.MaxNotesLength);
        builder.HasIndex(e => new { e.TenantId, e.Code }).IsUnique();
        builder.HasIndex(e => new { e.TenantId, e.Name });
    }

    /// <summary>Value object or list of records stored as a <c>jsonb</c> column.</summary>
    public static PropertyBuilder<TProperty> HasJson<TEntity, TProperty>(this EntityTypeBuilder<TEntity> builder, Expression<Func<TEntity, TProperty>> property, bool required = true)
        where TEntity : class
    {
        var converter = new ValueConverter<TProperty, string>(
            value => JsonSerializer.Serialize(value, Json),
            json => JsonSerializer.Deserialize<TProperty>(json, Json)!);

        var comparer = new ValueComparer<TProperty>(
            (a, b) => JsonSerializer.Serialize(a, Json) == JsonSerializer.Serialize(b, Json),
            value => value == null ? 0 : JsonSerializer.Serialize(value, Json).GetHashCode(),
            value => JsonSerializer.Deserialize<TProperty>(JsonSerializer.Serialize(value, Json), Json)!);

        var propertyBuilder = builder.Property(property)
            .HasConversion(converter, comparer)
            .HasColumnType("jsonb");

        return required ? propertyBuilder.IsRequired() : propertyBuilder;
    }

    /// <summary>List of ids or texts stored as a native PostgreSQL array (queries can use <c>Contains</c>).</summary>
    public static void HasArray<TEntity, TElement>(this EntityTypeBuilder<TEntity> builder, Expression<Func<TEntity, IReadOnlyList<TElement>>> property, string field)
        where TEntity : class =>
        builder.PrimitiveCollection(property).HasField(field).UsePropertyAccessMode(PropertyAccessMode.Field).IsRequired();
}
