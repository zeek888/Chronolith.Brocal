import { HttpClient, HttpHeaders, HttpParams, HttpResponse } from '@angular/common/http';
import { Injectable, inject, signal } from '@angular/core';
import { Observable, map, tap } from 'rxjs';
import { ApprovalNotices } from './approvals';
import { apiUrl } from './config';
import { FileCategory, UploadedFile } from './models';

export type QueryValue = string | number | boolean | null | undefined | readonly (string | number)[];
export type Query = Record<string, QueryValue>;

export interface DownloadedFile {
  name: string;
  content: Blob;
}

interface CallOptions {
  /** Send the company header (default true). Platform and session calls work without a company. */
  tenant?: boolean;
}

/** Company the user works on; every call carries it in `X-Tenant` (id or slug). */
@Injectable({ providedIn: 'root' })
export class TenantHeader {
  readonly slug = signal<string | null>(null);
}

/**
 * Thin wrapper over the HttpClient of the host. Inside ChronoLith it is the Shell's client (token and
 * language added by its interceptors); in standalone mode the client of the Brocal application.
 */
@Injectable({ providedIn: 'root' })
export class BrocalApi {
  private readonly http = inject(HttpClient);
  private readonly tenant = inject(TenantHeader);
  private readonly notices = inject(ApprovalNotices);

  get<T>(path: string, query?: Query, options?: CallOptions): Observable<T> {
    return this.http.get<T>(apiUrl(path), { params: toParams(query), headers: this.headers(options) });
  }

  /** A 202 answer (action held by an approval workflow) shows its message; the caller still gets the body. */
  post<T>(path: string, body: unknown = null, options?: CallOptions): Observable<T> {
    return this.http.post<T>(apiUrl(path), body, { headers: this.headers(options) }).pipe(tap((answer) => this.notices.notify(answer)));
  }

  put<T>(path: string, body: unknown = null, options?: CallOptions): Observable<T> {
    return this.http.put<T>(apiUrl(path), body, { headers: this.headers(options) }).pipe(tap((answer) => this.notices.notify(answer)));
  }

  delete<T>(path: string, query?: Query, options?: CallOptions): Observable<T> {
    return this.http.delete<T>(apiUrl(path), { params: toParams(query), headers: this.headers(options) });
  }

  /** Files generated by the API (PDF, Excel, XML, ZIP) with the name it suggests. */
  download(path: string, query?: Query, body?: unknown, fallbackName = 'archivo'): Observable<DownloadedFile> {
    const headers = this.headers();
    const request: Observable<HttpResponse<Blob>> =
      body === undefined
        ? this.http.get(apiUrl(path), { params: toParams(query), headers, observe: 'response', responseType: 'blob' })
        : this.http.post(apiUrl(path), body, { params: toParams(query), headers, observe: 'response', responseType: 'blob' });
    return request.pipe(map((response) => toFile(response, fallbackName)));
  }

  /** Photos, signatures, permits, receipts and logos of the company. */
  upload(content: Blob, fileName: string, category: FileCategory): Observable<UploadedFile> {
    const form = new FormData();
    form.append('file', content, fileName);
    form.append('category', category);
    return this.http.post<UploadedFile>(apiUrl('files'), form, { headers: this.headers() });
  }

  private headers(options?: CallOptions): HttpHeaders | undefined {
    const slug = this.tenant.slug();
    return options?.tenant === false || !slug ? undefined : new HttpHeaders({ 'X-Tenant': slug });
  }
}

export function toParams(query?: Query): HttpParams {
  let params = new HttpParams();
  for (const [key, value] of Object.entries(query ?? {})) {
    if (value === null || value === undefined || value === '') {
      continue;
    }

    if (Array.isArray(value)) {
      for (const item of value) {
        params = params.append(key, String(item));
      }
    } else {
      params = params.set(key, String(value));
    }
  }

  return params;
}

function toFile(response: HttpResponse<Blob>, fallbackName: string): DownloadedFile {
  const disposition = response.headers.get('Content-Disposition') ?? '';
  const utf8 = /filename\*=UTF-8''([^;]+)/i.exec(disposition);
  const plain = /filename="?([^";]+)"?/i.exec(disposition);
  const name = utf8 ? decodeURIComponent(utf8[1]) : (plain?.[1] ?? fallbackName);
  return { name, content: response.body ?? new Blob() };
}

export function saveFile(file: DownloadedFile): void {
  const url = URL.createObjectURL(file.content);
  const link = document.createElement('a');
  link.href = url;
  link.download = file.name;
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Opens a PDF or image in a new tab (the blob keeps the session out of the URL). */
export function openFile(file: DownloadedFile): void {
  const url = URL.createObjectURL(file.content);
  window.open(url, '_blank', 'noopener');
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}
